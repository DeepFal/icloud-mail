var ErrMailRegistryInput = errors.New("invalid mail registry input")
var ErrMailRegistryConflict = errors.New("mail registry conflict")

func (s *Store) migrateMailRegistry(ctx context.Context, tx *sql.Tx) error {
	id := "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
	if s.dialect == dialectSQLite {
		id = "INTEGER PRIMARY KEY AUTOINCREMENT"
	}
	statements := []string{
		`CREATE TABLE IF NOT EXISTS mailbox_notes (address TEXT PRIMARY KEY, note TEXT NOT NULL DEFAULT '', updated_at BIGINT NOT NULL)`,
		fmt.Sprintf(`CREATE TABLE IF NOT EXISTS mail_services (id %s, name TEXT NOT NULL, name_key TEXT NOT NULL UNIQUE, domain TEXT NOT NULL DEFAULT '', note TEXT NOT NULL DEFAULT '', archived BOOLEAN NOT NULL DEFAULT FALSE, created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL)`, id),
		fmt.Sprintf(`CREATE TABLE IF NOT EXISTS mailbox_service_registrations (id %s, address TEXT NOT NULL, service_id BIGINT NOT NULL REFERENCES mail_services(id), account_identifier TEXT NOT NULL DEFAULT '', account_key TEXT NOT NULL, status TEXT NOT NULL CHECK(status IN ('registered','pending','closed','not_registered')), note TEXT NOT NULL DEFAULT '', created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL, UNIQUE(address,service_id,account_key), CHECK(status <> 'not_registered' OR account_key=''))`, id),
		`CREATE INDEX IF NOT EXISTS mailbox_service_registrations_service_idx ON mailbox_service_registrations(service_id,address,status)`,
	}
	for _, statement := range statements {
		if _, err := s.txExecContext(ctx, tx, statement); err != nil {
			return fmt.Errorf("migrate mail registry: %w", err)
		}
	}
	return nil
}
func registryText(value string, max int, multiline bool) (string, error) {
	if !utf8.ValidString(value) {
		return "", ErrMailRegistryInput
	}
	value = strings.TrimSpace(value)
	if utf8.RuneCountInString(value) > max {
		return "", ErrMailRegistryInput
	}
	for _, r := range value {
		if unicode.IsControl(r) && (!multiline || (r != '\n' && r != '\r' && r != '\t')) {
			return "", ErrMailRegistryInput
		}
	}
	return value, nil
}
func registryKey(value string) string {
	return strings.ToLower(norm.NFKC.String(strings.TrimSpace(value)))
}
func registryDomain(value string) (string, error) {
	value = strings.TrimSpace(value)
	if value == "" {
		return "", nil
	}
	ascii, err := idna.Lookup.ToASCII(strings.ToLower(value))
	if err != nil || len(ascii) > 253 || strings.ContainsAny(ascii, "/:?@#%\\ \t\r\n") {
		return "", fmt.Errorf("%w: 域名只填写主机名，例如 github.com", ErrMailRegistryInput)
	}
	for _, label := range strings.Split(ascii, ".") {
		if len(label) == 0 || len(label) > 63 || label[0] == '-' || label[len(label)-1] == '-' {
			return "", ErrMailRegistryInput
		}
		for _, r := range label {
			if !((r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '-') {
				return "", ErrMailRegistryInput
			}
		}
	}
	return ascii, nil
}
func normalizeMailService(value domain.MailService) (domain.MailService, error) {
	var err error
	value.Name, err = registryText(value.Name, 100, false)
	if err != nil || value.Name == "" {
		return value, fmt.Errorf("%w: 服务名称必填且最多100个字符", ErrMailRegistryInput)
	}
	value.Domain, err = registryDomain(value.Domain)
	if err != nil {
		return value, err
	}
	value.Note, err = registryText(value.Note, 2000, true)
	if err != nil {
		return value, fmt.Errorf("%w: 说明最多2000个字符，不能包含控制字符", ErrMailRegistryInput)
	}
	return value, nil
}
func registryReadError(err error) error {
	if errors.Is(err, sql.ErrNoRows) {
		return ErrNotFound
	}
	return err
}
func scanMailService(row rowScanner) (domain.MailService, error) {
	var value domain.MailService
	var created, updated int64
	err := row.Scan(&value.ID, &value.Name, &value.Domain, &value.Note, &value.Archived, &created, &updated)
	if err != nil {
		return value, registryReadError(err)
	}
	value.CreatedAt = timeFromTimestamp(created)
	value.UpdatedAt = timeFromTimestamp(updated)
	return value, nil
}

const mailServiceColumns = `id,name,domain,note,archived,created_at,updated_at`

func (s *Store) GetMailService(ctx context.Context, id int64) (domain.MailService, error) {
	if id < 1 {
		return domain.MailService{}, ErrNotFound
	}
	return scanMailService(s.queryRowContext(ctx, `SELECT `+mailServiceColumns+` FROM mail_services WHERE id=?`, id))
}
func (s *Store) ListMailServices(ctx context.Context, query string, includeArchived bool) ([]domain.MailService, error) {
	query, err := registryText(query, 200, false)
	if err != nil {
		return nil, err
	}
	pattern := workspaceLike(query)
	rows, err := s.queryContext(ctx, `SELECT `+mailServiceColumns+` FROM mail_services WHERE (? OR archived=FALSE) AND (LOWER(name) LIKE ? ESCAPE '!' OR LOWER(domain) LIKE ? ESCAPE '!' OR LOWER(note) LIKE ? ESCAPE '!') ORDER BY name_key,id`, includeArchived, pattern, pattern, pattern)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	items := make([]domain.MailService, 0)
	for rows.Next() {
		item, e := scanMailService(rows)
		if e != nil {
			return nil, e
		}
		items = append(items, item)
	}
	return items, rows.Err()
}
func (s *Store) CreateMailService(ctx context.Context, value domain.MailService) (domain.MailService, error) {
	value, err := normalizeMailService(value)
	if err != nil {
		return value, err
	}
	now := timestamp(s.now().UTC())
	err = s.queryRowContext(ctx, `INSERT INTO mail_services(name,name_key,domain,note,archived,created_at,updated_at) VALUES(?,?,?,?,?,?,?) RETURNING id`, value.Name, registryKey(value.Name), value.Domain, value.Note, value.Archived, now, now).Scan(&value.ID)
	if isUniqueConstraintError(err) {
		return value, fmt.Errorf("%w: 服务名称已存在，请选择已有服务", ErrMailRegistryConflict)
	}
	if err != nil {
		return value, err
	}
	return s.GetMailService(ctx, value.ID)
}
func (s *Store) UpdateMailService(ctx context.Context, id int64, value domain.MailService) (domain.MailService, error) {
	value, err := normalizeMailService(value)
	if err != nil {
		return value, err
	}
	result, err := s.execContext(ctx, `UPDATE mail_services SET name=?,name_key=?,domain=?,note=?,archived=?,updated_at=? WHERE id=?`, value.Name, registryKey(value.Name), value.Domain, value.Note, value.Archived, timestamp(s.now().UTC()), id)
	if isUniqueConstraintError(err) {
		return value, fmt.Errorf("%w: 服务名称已存在", ErrMailRegistryConflict)
	}
	if err != nil {
		return value, err
	}
	if err = requireAffected(result, "mail service"); err != nil {
		return value, err
	}
	return s.GetMailService(ctx, id)
}
func (s *Store) registryAddressTx(ctx context.Context, tx *sql.Tx, id int64) (string, error) {
	var address string
	err := s.txQueryRowContext(ctx, tx, `SELECT address FROM aliases WHERE id=?`, id).Scan(&address)
	return domain.NormalizeEmail(address), registryReadError(err)
}
func (s *Store) registryProfileTx(ctx context.Context, tx *sql.Tx, id int64) (domain.MailboxProfile, error) {
	profile := domain.MailboxProfile{AliasID: id, Registrations: make([]domain.ServiceRegistration, 0)}
	address, err := s.registryAddressTx(ctx, tx, id)
	if err != nil {
		return profile, err
	}
	profile.Address = address
	var at int64
	err = s.txQueryRowContext(ctx, tx, `SELECT note,updated_at FROM mailbox_notes WHERE address=?`, address).Scan(&profile.Note, &at)
	if err == nil {
		v := timeFromTimestamp(at)
		profile.UpdatedAt = &v
	} else if !errors.Is(err, sql.ErrNoRows) {
		return profile, err
	}
	rows, err := s.txQueryContext(ctx, tx, `SELECT r.id,r.service_id,svc.name,r.address,r.account_identifier,r.status,r.note,r.created_at,r.updated_at FROM mailbox_service_registrations r JOIN mail_services svc ON svc.id=r.service_id WHERE r.address=? ORDER BY svc.name_key,r.account_key,r.id`, address)
	if err != nil {
		return profile, err
	}
	defer rows.Close()
	for rows.Next() {
		var entry domain.ServiceRegistration
		var created, updated int64
		if err := rows.Scan(&entry.ID, &entry.ServiceID, &entry.ServiceName, &entry.Address, &entry.AccountIdentifier, &entry.Status, &entry.Note, &created, &updated); err != nil {
			return profile, err
		}
		entry.CreatedAt = timeFromTimestamp(created)
		entry.UpdatedAt = timeFromTimestamp(updated)
		profile.Registrations = append(profile.Registrations, entry)
	}
	return profile, rows.Err()
}
func (s *Store) GetMailboxProfile(ctx context.Context, id int64) (domain.MailboxProfile, error) {
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return domain.MailboxProfile{}, err
	}
	defer tx.Rollback()
	value, err := s.registryProfileTx(ctx, tx, id)
	if err != nil {
		return value, err
	}
	return value, tx.Commit()
}
func (s *Store) SetMailboxNote(ctx context.Context, id int64, note string) (domain.MailboxProfile, error) {
	note, err := registryText(note, 2000, true)
	if err != nil {
		return domain.MailboxProfile{}, fmt.Errorf("%w: 邮箱备注最多2000个字符", ErrMailRegistryInput)
	}
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return domain.MailboxProfile{}, err
	}
	defer tx.Rollback()
	address, err := s.registryAddressTx(ctx, tx, id)
	if err != nil {
		return domain.MailboxProfile{}, err
	}
	_, err = s.txExecContext(ctx, tx, `INSERT INTO mailbox_notes(address,note,updated_at) VALUES(?,?,?) ON CONFLICT(address) DO UPDATE SET note=excluded.note,updated_at=excluded.updated_at`, address, note, timestamp(s.now().UTC()))
	if err != nil {
		return domain.MailboxProfile{}, err
	}
	value, err := s.registryProfileTx(ctx, tx, id)
	if err != nil {
		return value, err
	}
	return value, tx.Commit()
}
func normalizeRegistration(input domain.ServiceRegistrationInput) (domain.ServiceRegistrationInput, error) {
	if input.ServiceID < 1 {
		return input, ErrMailRegistryInput
	}
	switch input.Status {
	case "registered", "pending", "closed", "not_registered":
	default:
		return input, ErrMailRegistryInput
	}
	var err error
	input.AccountIdentifier, err = registryText(input.AccountIdentifier, 200, false)
	if err != nil {
		return input, ErrMailRegistryInput
	}
	input.Note, err = registryText(input.Note, 2000, true)
	if err != nil {
		return input, ErrMailRegistryInput
	}
	if input.Status == "not_registered" && input.AccountIdentifier != "" {
		return input, fmt.Errorf("%w: 确认未注册时不应填写账号标识", ErrMailRegistryInput)
	}
	return input, nil
}
func (s *Store) SaveMailboxRegistration(ctx context.Context, id int64, input domain.ServiceRegistrationInput) (domain.MailboxProfile, error) {
	return s.saveMailboxRegistrations(ctx, []int64{id}, input)
}
func (s *Store) BatchSaveMailboxRegistrations(ctx context.Context, ids []int64, input domain.ServiceRegistrationInput) (int, error) {
	_, err := s.saveMailboxRegistrations(ctx, ids, input)
	if err != nil {
		return 0, err
	}
	return len(ids), nil
}
func (s *Store) saveMailboxRegistrations(ctx context.Context, ids []int64, input domain.ServiceRegistrationInput) (domain.MailboxProfile, error) {
	if len(ids) < 1 || len(ids) > 100 {
		return domain.MailboxProfile{}, ErrMailRegistryInput
	}
	input, err := normalizeRegistration(input)
	if err != nil {
		return domain.MailboxProfile{}, err
	}
	sorted := append([]int64(nil), ids...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i] < sorted[j] })
	for i, id := range sorted {
		if id < 1 || (i > 0 && sorted[i-1] == id) {
			return domain.MailboxProfile{}, ErrMailRegistryInput
		}
	}
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return domain.MailboxProfile{}, err
	}
	defer tx.Rollback()
	// Serialize registration mutations and service archiving on the same service.
	// This also makes negative-vs-positive conflict checks safe on PostgreSQL.
	lock := ""
	if s.dialect == dialectPostgres {
		lock = " FOR UPDATE"
	}
	var archived bool
	if err = s.txQueryRowContext(ctx, tx, `SELECT archived FROM mail_services WHERE id=?`+lock, input.ServiceID).Scan(&archived); err != nil {
		return domain.MailboxProfile{}, registryReadError(err)
	}
	for _, id := range sorted {
		address, err := s.registryAddressTx(ctx, tx, id)
		if err != nil {
			return domain.MailboxProfile{}, err
		}
		key := registryKey(input.AccountIdentifier)
		var existing int64
		err = s.txQueryRowContext(ctx, tx, `SELECT id FROM mailbox_service_registrations WHERE address=? AND service_id=? AND account_key=?`, address, input.ServiceID, key).Scan(&existing)
		if err != nil && !errors.Is(err, sql.ErrNoRows) {
			return domain.MailboxProfile{}, err
		}
		if archived && existing == 0 {
			return domain.MailboxProfile{}, fmt.Errorf("%w: 服务已归档，请恢复服务后新增登记", ErrMailRegistryConflict)
		}
		if input.Status == "not_registered" {
			var count int
			err = s.txQueryRowContext(ctx, tx, `SELECT COUNT(*) FROM mailbox_service_registrations WHERE address=? AND service_id=? AND (account_key<>'' OR status<>'not_registered')`, address, input.ServiceID).Scan(&count)
			if err != nil {
				return domain.MailboxProfile{}, err
			}
			if count > 0 {
				return domain.MailboxProfile{}, fmt.Errorf("%w: 该邮箱已有使用记录，不能改成确认未注册。请先核实并移除原登记", ErrMailRegistryConflict)
			}
		} else {
			if _, err = s.txExecContext(ctx, tx, `DELETE FROM mailbox_service_registrations WHERE address=? AND service_id=? AND status='not_registered'`, address, input.ServiceID); err != nil {
				return domain.MailboxProfile{}, err
			}
		}
		now := timestamp(s.now().UTC())
		_, err = s.txExecContext(ctx, tx, `INSERT INTO mailbox_service_registrations(address,service_id,account_identifier,account_key,status,note,created_at,updated_at) VALUES(?,?,?,?,?,?,?,?) ON CONFLICT(address,service_id,account_key) DO UPDATE SET account_identifier=excluded.account_identifier,status=excluded.status,note=excluded.note,updated_at=excluded.updated_at`, address, input.ServiceID, input.AccountIdentifier, key, input.Status, input.Note, now, now)
		if err != nil {
			return domain.MailboxProfile{}, err
		}
	}
	value, err := s.registryProfileTx(ctx, tx, ids[0])
	if err != nil {
		return value, err
	}
	return value, tx.Commit()
}
func (s *Store) DeleteMailboxRegistration(ctx context.Context, id, registrationID int64) (domain.MailboxProfile, error) {
	if id < 1 || registrationID < 1 {
		return domain.MailboxProfile{}, ErrMailRegistryInput
	}
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return domain.MailboxProfile{}, err
	}
	defer tx.Rollback()
	address, err := s.registryAddressTx(ctx, tx, id)
	if err != nil {
		return domain.MailboxProfile{}, err
	}
	var serviceID int64
	err = s.txQueryRowContext(ctx, tx, `SELECT service_id FROM mailbox_service_registrations WHERE id=? AND address=?`, registrationID, address).Scan(&serviceID)
	if err != nil {
		return domain.MailboxProfile{}, registryReadError(err)
	}
	lock := ""
	if s.dialect == dialectPostgres {
		lock = " FOR UPDATE"
	}
	var locked int64
	if err = s.txQueryRowContext(ctx, tx, `SELECT id FROM mail_services WHERE id=?`+lock, serviceID).Scan(&locked); err != nil {
		return domain.MailboxProfile{}, err
	}
	result, err := s.txExecContext(ctx, tx, `DELETE FROM mailbox_service_registrations WHERE id=? AND address=?`, registrationID, address)
	if err != nil {
		return domain.MailboxProfile{}, err
	}
	if err = requireAffected(result, "service registration"); err != nil {
		return domain.MailboxProfile{}, err
	}
	value, err := s.registryProfileTx(ctx, tx, id)
	if err != nil {
		return value, err
	}
	return value, tx.Commit()
}
func (s *Store) ListServiceMailboxes(ctx context.Context, f domain.ServiceMailboxFilter) (domain.ServiceMailboxPage, error) {
	page := domain.ServiceMailboxPage{Items: make([]domain.ServiceMailbox, 0)}
	if f.ServiceID < 1 || f.AccountID < 0 || f.GroupID < 0 || f.Offset < 0 || f.Offset > 1000000 || f.Limit > 200 {
		return page, ErrMailRegistryInput
	}
	if f.Limit <= 0 {
		f.Limit = 50
	}
	switch f.Status {
	case "", "unrecorded", "registered", "pending", "closed", "not_registered":
	default:
		return page, ErrMailRegistryInput
	}
	query, err := registryText(f.Query, 200, false)
	if err != nil {
		return page, err
	}
	if _, err = s.GetMailService(ctx, f.ServiceID); err != nil {
		return page, err
	}
	// Aggregate only the chosen service; the left join retains addresses with no
	// records, which are unknown (unrecorded), never automatically not_registered.
	base := ` FROM aliases al JOIN accounts ac ON ac.id=al.account_id LEFT JOIN mail_groups mg ON mg.id=al.group_id LEFT JOIN mailbox_notes mn ON mn.address=al.address LEFT JOIN (SELECT address,COUNT(*) AS registration_count,CASE WHEN SUM(CASE WHEN status='registered' THEN 1 ELSE 0 END)>0 THEN 'registered' WHEN SUM(CASE WHEN status='pending' THEN 1 ELSE 0 END)>0 THEN 'pending' WHEN SUM(CASE WHEN status='closed' THEN 1 ELSE 0 END)>0 THEN 'closed' ELSE 'not_registered' END AS status FROM mailbox_service_registrations WHERE service_id=? GROUP BY address) summary ON summary.address=al.address WHERE 1=1`
	args := []any{f.ServiceID}
	if f.Status != "" {
		base += ` AND COALESCE(summary.status,'unrecorded')=?`
		args = append(args, f.Status)
	}
	if f.AccountID > 0 {
		base += ` AND al.account_id=?`
		args = append(args, f.AccountID)
	}
	if f.GroupID > 0 {
		base += ` AND al.group_id=?`
		args = append(args, f.GroupID)
	}
	if f.EnabledOnly {
		base += ` AND al.enabled=TRUE AND ac.enabled=TRUE`
	}
	if query != "" {
		pattern := workspaceLike(query)
		base += ` AND (LOWER(al.address) LIKE ? ESCAPE '!' OR LOWER(al.label) LIKE ? ESCAPE '!' OR LOWER(COALESCE(mn.note,'')) LIKE ? ESCAPE '!' OR EXISTS(SELECT 1 FROM mailbox_service_registrations search WHERE search.address=al.address AND search.service_id=? AND (LOWER(search.account_identifier) LIKE ? ESCAPE '!' OR LOWER(search.note) LIKE ? ESCAPE '!')))`
		args = append(args, pattern, pattern, pattern, f.ServiceID, pattern, pattern)
	}
	if err = s.queryRowContext(ctx, `SELECT COUNT(*)`+base, args...).Scan(&page.Total); err != nil {
		return page, err
	}
	rows, err := s.queryContext(ctx, `SELECT al.id,al.account_id,al.address,al.label,COALESCE(mn.note,''),(al.enabled AND ac.enabled),COALESCE(mg.name,''),COALESCE(summary.status,'unrecorded'),COALESCE(summary.registration_count,0)`+base+` ORDER BY al.address,al.id LIMIT ? OFFSET ?`, append(args, f.Limit, f.Offset)...)
	if err != nil {
		return page, err
	}
	defer rows.Close()
	for rows.Next() {
		var item domain.ServiceMailbox
		if err = rows.Scan(&item.AliasID, &item.AccountID, &item.Address, &item.AliasLabel, &item.Note, &item.Enabled, &item.GroupName, &item.Status, &item.RegistrationCount); err != nil {
			return page, err
		}
		page.Items = append(page.Items, item)
	}
	page.HasMore = f.Offset+len(page.Items) < page.Total
	return page, rows.Err()
}
